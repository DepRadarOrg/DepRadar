    /// npm: an optional `@scope/` prefix, then a name, each made of
    /// `a-z 0-9 - . _ ~` and not starting with `.` or `_`; at most 214
    /// characters in total.
    fn is_valid_npm_name(name: &str) -> bool {
        fn is_valid_part(part: &str) -> bool {
            !part.is_empty()
                && !part.starts_with(['.', '_'])
                && part
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || "-._~".contains(c))
        }

        if name.len() > 214 {
            return false;
        }
        match name.strip_prefix('@') {
            Some(scoped) => match scoped.split_once('/') {
                Some((scope, rest)) => is_valid_part(scope) && is_valid_part(rest),
                None => false,
            },
            None => is_valid_part(name),
        }
    }

    /// PyPI (PEP 508): `a-z 0-9 - . _`, starting and ending with a letter or
    /// digit.
    fn is_valid_pypi_name(name: &str) -> bool {
        let is_alnum = |c: char| c.is_ascii_lowercase() || c.is_ascii_digit();
        name.starts_with(is_alnum)
            && name.ends_with(is_alnum)
            && name.chars().all(|c| is_alnum(c) || "-._".contains(c))
    }

    /// crates.io: an ASCII letter followed by letters, digits, `-` or `_`; at
    /// most 64 characters.
    fn is_valid_crate_name(name: &str) -> bool {
        name.len() <= 64
            && name.starts_with(|c: char| c.is_ascii_lowercase())
            && name
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || "-_".contains(c))
    }

    /// RubyGems: `a-z 0-9 - . _`, starting with a letter or digit.
    fn is_valid_gem_name(name: &str) -> bool {
        name.starts_with(|c: char| c.is_ascii_lowercase() || c.is_ascii_digit())
            && name
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || "-._".contains(c))
    }

    /// Go modules: a slash-separated import path whose segments are made of
    /// `a-z 0-9 - . _ ~`, none empty, and the whole path lowercase.
    fn is_valid_go_module_name(name: &str) -> bool {
        !name.is_empty()
            && name.split('/').all(|segment| {
                !segment.is_empty()
                    && segment
                        .chars()
                        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || "-._~".contains(c))
            })
    }

    /// Packagist: `vendor/package`, each part made of `a-z 0-9 - . _`, not
    /// empty and starting with a letter or digit.
    fn is_valid_packagist_name(name: &str) -> bool {
        fn is_valid_part(part: &str) -> bool {
            part.starts_with(|c: char| c.is_ascii_lowercase() || c.is_ascii_digit())
                && part
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || "-._".contains(c))
        }

        match name.split_once('/') {
            Some((vendor, package)) => is_valid_part(vendor) && is_valid_part(package),
            None => false,
        }
    }

    /// PEP 503 normalisation: runs of `-`, `_` and `.` collapse to one `-`,
    /// so `ruamel.yaml` and `ruamel-yaml` are the same project.
    fn normalize_pypi_name(name: &str) -> String {
        let mut out = String::with_capacity(name.len());
        for c in name.chars() {
            if "-_.".contains(c) {
                if !out.ends_with('-') {
                    out.push('-');
                }
            } else {
                out.push(c.to_ascii_lowercase());
            }
        }
        out
    }

    /// Returns every problem with one dataset, one line per bad entry.
    fn dataset_problems(dataset: &Dataset) -> Vec<String> {
        let mut problems = Vec::new();

        // The loader's hand-rolled parser accepts anything, so check the file
        // really is a JSON object with a `packages` array of strings and that
        // both parsers agree.
        match serde_json::from_str::<serde_json::Value>(dataset.raw) {
            Ok(value) => match value.get("packages").and_then(|p| p.as_array()) {
                Some(array) => {
                    let strict: Vec<String> = array
                        .iter()
                        .filter_map(|v| v.as_str().map(str::to_string))
                        .collect();
                    if strict.len() != array.len() {
                        problems.push("packages array contains non-string entries".into());
                    } else if strict != parse_dataset(dataset.raw) {
                        problems.push(
                            "loader parses the file differently from serde_json".into(),
                        );
                    }
                }
                None => problems.push("missing `packages` array".into()),
            },
            Err(err) => problems.push(format!("not a JSON object: {err}")),
        }

        if generated_at(dataset.raw).is_none() {
            problems.push("missing `generated_at` date".into());
        }

        let names = parse_dataset(dataset.raw);
        if names.is_empty() {
            problems.push("no entries".into());
        }

        let mut seen = HashSet::new();
        for name in &names {
            if name.trim() != name {
                problems.push(format!("{name:?}: leading or trailing whitespace"));
            }
            if name.to_lowercase() != *name {
                problems.push(format!("{name:?}: not lowercase"));
            }
            if !(dataset.is_valid_name)(name) {
                problems.push(format!("{name:?}: not a valid name on this registry"));
            }
            if !seen.insert((dataset.identity)(name)) {
                problems.push(format!("{name:?}: duplicate entry"));
            }
        }

        problems
    }

