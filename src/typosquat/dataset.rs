//! Bundled lists of popular npm, PyPI, crates.io, RubyGems, Go module and
//! Packagist package names.
//!
//! Typosquatting attacks work by publishing a package whose name is one edit
//! away from something popular (`reqeusts`, `expresss`, `lodahs`). Detecting
//! that needs a reference set of "names worth imitating" to compare against.
//! This module ships that reference set as one JSON array per registry under
//! `data/popular-packages/` and exposes a single loader that returns them as
//! one combined list.
//!
//! Each list is the registry's top packages (npm: top 5000, others: top
//! 1000), ordered most-downloaded first and regenerated by
//! `scripts/update-datasets.py` (see `data/popular-packages/README.md` for the
//! sources). [`popularity_rank`] relies on that ordering; nothing else depends
//! on the exact order or count.
//!
//! Every dataset also records the date it was generated (`generated_at`), so
//! CI can fail when a list has gone stale — see [`dataset_age_days`] and the
//! `datasets_are_not_stale` test.

use std::sync::OnceLock;

/// Raw JSON text of the npm popular-package list, embedded at compile time.
const NPM_TOP_PACKAGES_JSON: &str = include_str!("../../data/popular-packages/npm-top5000.json");

/// Raw JSON text of the PyPI popular-package list, embedded at compile time.
const PYPI_TOP_PACKAGES_JSON: &str = include_str!("../../data/popular-packages/pypi-top1000.json");

/// Raw JSON text of the crates.io popular-package list, embedded at compile
/// time.
const CRATES_TOP_PACKAGES_JSON: &str =
    include_str!("../../data/popular-packages/crates-top1000.json");

/// Raw JSON text of the RubyGems popular-package list, embedded at compile
/// time.
const RUBYGEMS_TOP_PACKAGES_JSON: &str =
    include_str!("../../data/popular-packages/rubygems-top1000.json");

/// Raw JSON text of the Go module popular-package list, embedded at compile
/// time.
const GO_TOP_PACKAGES_JSON: &str = include_str!("../../data/popular-packages/go-top1000.json");

/// Raw JSON text of the Packagist popular-package list, embedded at compile
/// time.
const PACKAGIST_TOP_PACKAGES_JSON: &str =
    include_str!("../../data/popular-packages/packagist-top1000.json");

/// Raw JSON text of the allowlist of legitimate near-collisions, embedded at
/// compile time.
#[allow(dead_code)]
