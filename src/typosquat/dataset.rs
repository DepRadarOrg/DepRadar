    #[test]
    fn dataset_age_days_computes_whole_days() {
        assert_eq!(dataset_age_days("2024-01-01", "2024-01-01"), Some(0));
        assert_eq!(dataset_age_days("2024-01-01", "2024-01-31"), Some(30));
        assert_eq!(dataset_age_days("2024-01-01", "2024-07-01"), Some(182));
        // Leap day is counted.
        assert_eq!(dataset_age_days("2024-02-28", "2024-03-01"), Some(2));
        // A future date yields a negative age.
        assert_eq!(dataset_age_days("2024-01-02", "2024-01-01"), Some(-1));
        // Malformed dates are rejected.
        assert_eq!(dataset_age_days("not-a-date", "2024-01-01"), None);
        assert_eq!(dataset_age_days("2024-01-01", "2024-13-01"), None);
    }

    #[test]
    fn staleness_check_fails_on_old_date_and_passes_on_today() {
        // An old date is stale.
        let old_age = dataset_age_days("2020-01-01", "2024-01-01").unwrap();
        assert!(
            old_age > MAX_DATASET_AGE_DAYS,
            "expected 2020-01-01 to be stale by 2024-01-01"
        );

        // Today's date is fresh.
        let today_age = dataset_age_days("2024-01-01", "2024-01-01").unwrap();
        assert!(
            today_age <= MAX_DATASET_AGE_DAYS,
            "expected today's date to be fresh"
        );
    }

    #[test]
    fn datasets_are_not_stale() {
        // `today` is taken from the build environment's clock via the
        // `SOURCE_DATE_EPOCH`-independent `SystemTime`, formatted as a date.
        let today = current_date();
        let mut report = Vec::new();
        for dataset in DATASETS {
            let date = match generated_at(dataset.raw) {
                Some(date) => date,
                None => {
                    report.push(format!("{}: missing generated_at", dataset.file));
                    continue;
                }
            };
            match dataset_age_days(&date, &today) {
                Some(age) if age > MAX_DATASET_AGE_DAYS => report.push(format!(
                    "{}: generated_at {date} is {age} days old (max {MAX_DATASET_AGE_DAYS}); \
                     regenerate with scripts/update-datasets.py",
                    dataset.file
                )),
                Some(_) => {}
                None => report.push(format!(
                    "{}: generated_at {date:?} is not a YYYY-MM-DD date",
                    dataset.file
                )),
            }
        }
        assert!(
            report.is_empty(),
            "stale datasets in data/popular-packages/:\n  {}",
            report.join("\n  ")
        );
    }

    /// Today's date as `YYYY-MM-DD`, derived from the system clock.
    fn current_date() -> String {
        let secs = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .expect("system clock is before the Unix epoch")
            .as_secs() as i64;
        let days = secs.div_euclid(86_400);
        let (year, month, day) = civil_from_days(days);
        format!("{year:04}-{month:02}-{day:02}")
    }

    /// Inverse of [`days_from_civil`]: `(year, month, day)` for a day count
    /// since 1970-01-01.
    fn civil_from_days(days: i64) -> (i64, u32, u32) {
        let z = days + 719_468;
        let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
        let doe = z - era * 146_097; // [0, 146096]
        let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365; // [0, 399]
        let y = yoe + era * 400;
        let doy = doe - (365 * yoe + yoe / 4 - yoe / 100); // [0, 365]
        let mp = (5 * doy + 2) / 153; // [0, 11]
        let d = doy - (153 * mp + 2) / 5 + 1; // [1, 31]
        let m = if mp < 10 { mp + 3 } else { mp - 9 }; // [1, 12]
        (if m <= 2 { y + 1 } else { y }, m as u32, d as u32)
    }

